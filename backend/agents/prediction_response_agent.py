"""
prediction_response_agent.py

AGENT 1 — ML Prediction Response Agent

Purpose:
    Receives the JSON output generated by your ML model,
    automatically sends that JSON to the LLM,
    generates a human-readable explanation,
    and returns a UI-ready JSON response.

Important:
    This agent DOES NOT perform the ML prediction.

    ML Model = prediction source of truth
    LLM      = explanation / interpretation layer
"""

import os
import json
from typing import Any, Dict, Optional

from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI


# ============================================================
# ENVIRONMENT
# ============================================================

load_dotenv()

GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")

LLM_MODEL = os.getenv(
    "LLM_MODEL",
    "gemini-2.5-flash"
)


# ============================================================
# SYSTEM PROMPT
# ============================================================

SYSTEM_PROMPT = """
You are the AI Prediction Explanation Agent for the
"Lahore City Intelligence Platform".

PROJECT MISSION:
"Predicting Problems Before They Happen."

Your job is to explain the result produced by a trusted
Machine Learning model.

IMPORTANT:

The ML model has already performed the prediction.

You MUST NOT:
- perform another prediction
- modify the ML risk score
- modify the ML risk level
- invent model outputs
- contradict the prediction JSON
- claim that you are the ML model
- invent real-time information

The ML prediction JSON is the source of truth.

You SHOULD:

1. Explain the predicted risk clearly.
2. Explain the risk score.
3. Explain the risk level.
4. Explain important input factors.
5. Explain why those factors may contribute to the risk.
6. Explain the likely situation in simple language.
7. Give practical recommendations.
8. Give priority/action guidance.
9. Make the response understandable to both technical
   and non-technical users.
10. Clearly distinguish prediction from recommendation.

Risk scale:

0-39   = LOW
40-69  = MODERATE
70-84  = HIGH
85-100 = CRITICAL

If the prediction JSON contains a risk type, explain it.

Possible risk types include:

- Flood
- Air Pollution
- Traffic
- Environmental
- Population Exposure
- Weather
- Infrastructure
- Combined/Multiple Risk

If information is missing from the JSON, do not invent it.

Return a professional, concise but useful explanation.

The response will be displayed directly to a user
inside a web/mobile application.
"""


# ============================================================
# AGENT CLASS
# ============================================================

class PredictionResponseAgent:
    """
    Agent responsible for converting ML prediction JSON
    into a human-readable AI explanation.

    Input:
        Prediction JSON from ML model

    Output:
        UI-ready JSON
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None
    ):

        self.api_key = (
            api_key
            or GEMINI_API_KEY
        )

        self.model_name = (
            model
            or LLM_MODEL
        )

        if not self.api_key:
            raise ValueError(
                "GEMINI_API_KEY is missing. "
                "Add it to your .env file."
            )

        self.llm = ChatGoogleGenerativeAI(

            model=self.model_name,

            google_api_key=self.api_key,

            temperature=0.2,

            max_output_tokens=1200,
        )

    # ========================================================
    # VALIDATE PREDICTION JSON
    # ========================================================

    @staticmethod
    def validate_prediction(
        prediction_json: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Validate the JSON received from the ML model.

        The prediction must contain at least a risk score
        or risk level.
        """

        if not isinstance(
            prediction_json,
            dict
        ):
            raise ValueError(
                "prediction_json must be a dictionary."
            )

        prediction = prediction_json.get(
            "prediction",
            prediction_json
        )

        if not isinstance(
            prediction,
            dict
        ):
            raise ValueError(
                "Invalid prediction structure."
            )

        if (
            "risk_score" not in prediction
            and "risk_level" not in prediction
        ):
            raise ValueError(
                "Prediction JSON must contain "
                "'risk_score' or 'risk_level'."
            )

        return prediction_json

    # ========================================================
    # GENERATE LLM EXPLANATION
    # ========================================================

    def generate_explanation(
        self,
        prediction_json: Dict[str, Any]
    ) -> str:
        """
        Send the ML JSON automatically to the LLM.
        """

        prompt = f"""
The following JSON was generated by the trusted
Machine Learning prediction system.

DO NOT change the ML prediction.

ML PREDICTION JSON:

{json.dumps(
    prediction_json,
    indent=2,
    ensure_ascii=False
)}

Generate a user-friendly explanation.

Cover:

- What is the predicted risk?
- What is the risk score?
- What does the risk level mean?
- What are the important contributing factors?
- What should the user/authority do?
- What should be prioritized?

Do not invent information that does not exist
in the JSON.
"""

        response = self.llm.invoke(
            [
                (
                    "system",
                    SYSTEM_PROMPT
                ),
                (
                    "human",
                    prompt
                )
            ]
        )

        content = response.content

        # Some LLM integrations can return structured
        # content blocks instead of a plain string.
        if isinstance(
            content,
            list
        ):

            parts = []

            for item in content:

                if isinstance(
                    item,
                    dict
                ):

                    text = item.get(
                        "text"
                    )

                    if text:
                        parts.append(text)

                elif isinstance(
                    item,
                    str
                ):

                    parts.append(item)

            content = "\n".join(parts)

        return str(content).strip()

    # ========================================================
    # MAIN AGENT
    # ========================================================

    def run(
        self,
        prediction_json: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Complete Agent 1 pipeline.

        ML JSON
            ↓
        Validation
            ↓
        LLM
            ↓
        UI JSON
        """

        try:

            # ----------------------------------------------
            # 1. Validate ML output
            # ----------------------------------------------

            prediction_json = (
                self.validate_prediction(
                    prediction_json
                )
            )

            # ----------------------------------------------
            # 2. Extract prediction
            # ----------------------------------------------

            prediction = prediction_json.get(
                "prediction",
                prediction_json
            )

            # ----------------------------------------------
            # 3. Send JSON to LLM
            # ----------------------------------------------

            explanation = (
                self.generate_explanation(
                    prediction_json
                )
            )

            # ----------------------------------------------
            # 4. Create UI response
            # ----------------------------------------------

            return {

                "success": True,

                "agent":
                    "prediction_response_agent",

                "location":
                    prediction_json.get(
                        "location",
                        "Lahore"
                    ),

                # ORIGINAL ML RESULT
                # Never modify this.
                "prediction":
                    prediction,

                # AI-generated explanation
                "ai_response":
                    explanation,

                # Useful for frontend
                "ui": {

                    "risk_score":
                        prediction.get(
                            "risk_score"
                        ),

                    "risk_level":
                        prediction.get(
                            "risk_level"
                        ),

                    "risk_type":
                        prediction.get(
                            "risk_type"
                        ),

                    "title":
                        self._generate_title(
                            prediction
                        ),

                    "explanation":
                        explanation,

                }
            }

        except Exception as e:

            return {

                "success": False,

                "agent":
                    "prediction_response_agent",

                "error":
                    str(e),

            }

    # ========================================================
    # UI TITLE
    # ========================================================

    @staticmethod
    def _generate_title(
        prediction: Dict[str, Any]
    ) -> str:

        risk_level = prediction.get(
            "risk_level"
        )

        risk_type = prediction.get(
            "risk_type"
        )

        if risk_type and risk_level:

            return (
                f"{risk_level} {risk_type} Risk"
            )

        if risk_level:

            return (
                f"{risk_level} Risk Detected"
            )

        return "Risk Prediction Result"


# ============================================================
# GLOBAL AGENT
# ============================================================

prediction_response_agent = (
    PredictionResponseAgent()
)


# ============================================================
# SIMPLE FUNCTION FOR FASTAPI / FLASK / UI
# ============================================================

def generate_prediction_response(
    prediction_json: Dict[str, Any]
) -> Dict[str, Any]:
    """
    Simple function that your API can call.

    Example:

        result = generate_prediction_response(
            ml_prediction
        )
    """

    return prediction_response_agent.run(
        prediction_json
    )


